#!/usr/bin/env python3
"""Emit tables (md + tex) and figures for round-2 experiments E1-E3."""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
OUT = HERE / "experiments_round2"
FIGS = HERE / "figures"
FIGS.mkdir(exist_ok=True)
PAPER = HERE / "paper"

plt.rcParams.update({
    'font.family': 'serif', 'font.size': 9,
    'axes.labelsize': 10, 'axes.titlesize': 10,
    'xtick.labelsize': 7.5, 'ytick.labelsize': 7.5, 'legend.fontsize': 7.5,
    'figure.dpi': 300, 'savefig.bbox': 'tight', 'savefig.pad_inches': .02})

E1 = json.loads((OUT / "e1_selection_procedures.json").read_text())
E2 = json.loads((OUT / "e2_matched_teacher.json").read_text())
E3 = json.loads((OUT / "e3_cost_quality.json").read_text())
DOMS = ["Video_Games", "Baby_Products", "Diginetica_HID"]
SHORT = {"Video_Games": "Video", "Baby_Products": "Baby",
         "Diginetica_HID": "Diginetica"}


# --------------------------------------------------------------------- E1
def emit_e1() -> None:
    md = ["# E1 — Selection-procedure comparison (test R@20)\n",
          "| Procedure | Budget | Video | Baby | Diginetica |",
          "|---|---|---|---|---|"]
    tex = [r"% Auto-generated by emit_round2_tables.py",
           r"\begin{table}[t]\centering\scriptsize",
           r"\caption{Selection-procedure comparison (test R@20; regret vs.\
 test-side oracle over the 15-cell allocation-control family). P2 uses one\
 training-learned scalar with zero validation cells.}",
           r"\label{tab:round2-procedures}",
           r"\setlength{\tabcolsep}{3pt}",
           r"\begin{tabular}{lr rrr rrr}", r"\hline",
           r"& & \multicolumn{3}{c}{Test R@20} & \multicolumn{3}{c}{Regret vs.\ oracle}\\",
           r"Procedure & Budget & Video & Baby & Digi. & Video & Baby & Digi.\\",
           r"\hline"]
    order = list(E1["domains"][DOMS[0]]["procedures"].keys())
    pretty = {
        "P1 endpoint-only (best of memory/neural)": "P1 endpoint-only",
        "P2 global-beta fusion (training-learned)": "P2 global-$\\beta$ fusion",
        "P3 regime router (short/long)": "P3 regime router",
        "P4 oracle over gate family (upper bound)": "P4 oracle (upper bnd.)",
        "P5 forced neural inclusion (fusion-only best)":
            "P5 forced neural incl.",
        "P6 query-conditioned gate (primary)": "P6 query-cond.\ gate",
    }
    for proc in order:
        cells_r, cells_g, budget = [], [], None
        for dom in DOMS:
            p = E1["domains"][dom]["procedures"][proc]
            budget = p["budget"]
            cells_r.append(f"{p['r20']:.5f}")
            cells_g.append(f"{p['regret_vs_oracle']:.5f}")
        md.append(f"| {pretty[proc].replace('$\\beta$','β')} | {budget} | "
                  + " | ".join(cells_r) + " | " +
                  " | ".join(c.lstrip('+') for c in cells_g) + " |")
        tex.append(f"{pretty[proc]} & {budget} & " + " & ".join(cells_r) +
                   " & " + " & ".join(cells_g) + r"\\")
    tex += [r"\hline", r"\end{tabular}", r"\end{table}"]
    md += [
        "",
        "**Fusion vs best endpoint, per seed (recomputed from frozen arrays):** "
        "Video 3/3 seeds, Baby 3/3 seeds (Diginetica endpoint arrays were "
        "lost in the incident; recorded means show memory .49428 > neural "
        ".44852 while fusion .51701).",
        "",
        "**Dynamic minus OOF-global ΔU [95% CI] (recorded paired bootstrap):**",
        "| Domain | ΔU | 95% CI |", "|---|---|---|"]
    for dom in DOMS:
        d = E1["domains"][dom]
        md.append(f"| {SHORT[dom]} | {d['dU_dynamic_minus_global']:+.5f} | "
                  f"[{d['dU_ci95'][0]:+.5f}, {d['dU_ci95'][1]:+.5f}] |")
    md += ["",
           "**Finding (report as-is):** the single training-learned global β "
           "(P2, zero validation cells) is within .00025 R@20 of the 15-cell "
           "oracle on every domain. The query-conditioned gate adds a "
           "detectable-but-tiny +.0002 U on Video (CI above zero) and is "
           "statistically undetectable on Baby and Diginetica. Endpoint-only "
           "selection (P1) loses .008–.023. Forbidding component rejection "
           "(P5) costs nothing here because fusion beats both endpoints on "
           "all domains and seeds."]
    (OUT / "e1_selection_procedures.md").write_text("\n".join(md))
    (PAPER / "round2_procedures.tex").write_text("\n".join(tex))


# --------------------------------------------------------------------- E2
def emit_e2() -> None:
    md = ["# E2 — Matched-information comparison\n",
          "## Same-teacher conditions (recorded, tab:metadata)\n",
          "| Condition | Init | Video | Baby |", "|---|---|---|---|"]
    tex = [r"% Auto-generated by emit_round2_tables.py",
           r"\begin{table}[t]\centering\small",
           r"\caption{Matched-information comparison and expert-swap\
 generality (test R@20). Upper block: same-teacher conditions. Lower block:\
 NARM replacing PASGR inside the identical memory/gate/fusion stack\
 (3 seeds).}",
           r"\label{tab:round2-matched}",
           r"\begin{tabular}{llrr}", r"\hline",
           r"Condition & Init & Video & Baby\\", r"\hline",
           r"NARM (ID-only) & random & .13705 & .02990\\",
           r"CEARF-N no-meta & random & .13208 & .05055\\",
           r"NARM+sem & TF--IDF & \textbf{.15387} & \textbf{.06628}\\",
           r"CEARF-N full & TF--IDF & .14700 & .05600\\",
           r"\hline",
           r"\multicolumn{4}{l}{\emph{Neural-expert swap (PASGR $\to$ NARM),"
           r" same memory+gate}}\\",
           r"NARM-only & ID & .13763 & .03880\\",
           r"gate fusion over NARM & ID & .14854 & .05001\\",
           r"fusion gain & & +.01091 & +.01121\\",
           r"\hline", r"\end{tabular}", r"\end{table}"]
    cond = [("NARM (ID-only)", "random",
             E2["domains"]["Video_Games"]["matched_teacher"]["narm_id"],
             E2["domains"]["Baby_Products"]["matched_teacher"]["narm_id"]),
            ("CEARF-N no-meta", "random",
             E2["domains"]["Video_Games"]["matched_teacher"]["cearfn_nometa"],
             E2["domains"]["Baby_Products"]["matched_teacher"]["cearfn_nometa"]),
            ("NARM+sem", "TF-IDF",
             E2["domains"]["Video_Games"]["matched_teacher"]["narm_sem"],
             E2["domains"]["Baby_Products"]["matched_teacher"]["narm_sem"]),
            ("CEARF-N full", "TF-IDF",
             E2["domains"]["Video_Games"]["matched_teacher"]["cearfn_full"],
             E2["domains"]["Baby_Products"]["matched_teacher"]["cearfn_full"])]
    for name, init, v, b in cond:
        md.append(f"| {name} | {init} | {v:.5f} | {b:.5f} |")
    md += ["",
           "## Expert swap — does fusion help a STRONG expert too? "
           "(recorded, 3 seeds)\n",
           "| Domain | NARM-only | Gate fusion | Gain | PASGR-only (ref) | "
           "Gain over PASGR |", "|---|---|---|---|---|---|"]
    for dom in DOMS:
        d = E2["domains"][dom]
        md.append(f"| {SHORT[dom]} | {d['expert_swap']['narm_only']:.5f} | "
                  f"{d['expert_swap']['dynamic']:.5f} | "
                  f"+{d['swap_fusion_gain_over_narm_only']:.5f} | "
                  f"{E1['domains'][dom]['procedures']['P1 endpoint-only (best of memory/neural)']['r20'] if False else ''}"
                  f"{'-'} | +{d['pasgr_fusion_gain_over_neural_only']:.5f} |")
    md += ["",
           "**Findings:** (1) metadata, not the fusion mechanism, drives most "
           "of the Amazon gain — NARM+sem beats CEARF-N full on both domains "
           "(+.0069 Video, +.0103 Baby). (2) Fusion is expert-strength-robust: "
           "on Diginetica NARM is the *stronger* expert (.53178 vs PASGR "
           ".44852) yet the same gate still adds +.00761. (3) Rescue/damage "
           "decomposition (recorded): Video 4451/1766, Baby 3889/1191, "
           "Diginetica 3076/1693 net rescues — fusion's gains come from "
           "concrete query-level rescues, not metric artifacts."]
    (OUT / "e2_matched_teacher.md").write_text("\n".join(md))
    (PAPER / "round2_matched.tex").write_text("\n".join(tex))


# --------------------------------------------------------------------- E3
def emit_e3() -> None:
    md = ["# E3 — Cost-quality audit\n",
          "R@20/MRR@20 recomputed from frozen arrays; budgets recorded.\n"]
    tex = [r"% Auto-generated by emit_round2_tables.py",
           r"\begin{table}[t]\centering\scriptsize",
           r"\caption{Cost--quality audit. Quality is recomputed from the"
           r" frozen v2/evidence per-query arrays (the allocation tables"
           r" report the separate dynamic-$\beta$ lineage); tuning budgets"
           r" are recorded from the audited grids; CEARF-N serving latency"
           r" is recorded on Apple M2 Pro (warm).}",
           r"\label{tab:round2-cost}",
           r"\setlength{\tabcolsep}{3pt}",
           r"\begin{tabular}{lrrrrr}", r"\hline",
           r"Method & Budget & R@20 (V) & R@20 (B) & R@20 (D) & MRR@20 (D)\\",
           r"\hline"]
    methods = sorted(E3["domains"]["Diginetica_HID"]["methods"].keys())
    pretty_name = {"gru4rec": "GRU4Rec", "narm": "NARM", "sasrec": "SASRec",
                   "sr_gnn": "SR-GNN",
                   "sigma_compatible": "SIGMA-compat.",
                   "memory": "Memory-only", "neural": "Neural-only",
                   "cearfn": "CEARF-N (v2 router)",
                   "continuous": "CEARF-N (v2 router)",
                   "regime": "v2 regime router",
                   "bucketed": "v2 bucketed router"}
    budget_map = {"GRU4Rec": "$\\leq$12 ep.", "NARM": "$\\leq$12 ep.",
                  "SASRec": "$\\leq$12 ep.", "SR-GNN": "$\\leq$5 ep.",
                  "SIGMA-compat.": "$\\leq$10 ep.",
                  "Memory-only": "6 profiles", "Neural-only": "16-cell grid",
                  "CEARF-N (v2 router)": "3 router cells",
                  "v2 regime router": "3 router cells",
                  "v2 bucketed router": "3 router cells"}
    for meth in methods:
        label = pretty_name.get(meth, meth)
        row, mrr_d = [], None
        for dom in DOMS:
            m = E3["domains"][dom]["methods"].get(meth)
            row.append(f"{m['r20_mean']:.4f}" if m else "--")
            if dom == "Diginetica_HID" and m:
                mrr_d = f"{m['mrr20_mean']:.4f}"
        budget = budget_map.get(label, "n/a")
        md.append(f"| {label} | {budget.replace('$\\leq$','<=')} | " +
                  " | ".join(row) + f" | {mrr_d or '--'} |")
        tex.append(f"{label} & {budget} & " + " & ".join(row) +
                   f" & {mrr_d or '--'}" + r"\\")
    rt = E3["domains"]["Video_Games"]["cearfn_serving_latency"]
    tex += [r"\hline",
            r"\multicolumn{6}{l}{\emph{CEARF-N serving latency (recorded):"
            f" gate {rt['gate_us']}~$\\mu$s, fusion {rt['post_us']}~$\\mu$s,"
            f" expert {rt['expert_ms']}~ms, total {rt['total_ms']}~ms/query"
            r" (Video; similar on Baby/Digi.)}}\\",
            r"\end{tabular}", r"\end{table}"]
    md += ["",
           f"**CEARF-N serving decomposition (recorded, Video):** gate "
           f"{rt['gate_us']} µs + fusion {rt['post_us']} µs + expert "
           f"{rt['expert_ms']} ms = {rt['total_ms']} ms/query — gate+fusion "
           "overhead is 2.3% of total; expert retrieval dominates.",
           "",
           "**Note:** per-baseline latency cannot be re-measured after the "
           "incident (datasets lost); the recorded figure "
           "`figures/fig_latency.pdf` remains the reference chart."]
    (OUT / "e3_cost_quality.md").write_text("\n".join(md))
    (PAPER / "round2_cost.tex").write_text("\n".join(tex))


# ------------------------------------------------------------------ figures
def figs() -> None:
    # E1: procedure bars with oracle line
    fig, axes = plt.subplots(1, 3, figsize=(10.5, 3.0))
    order = list(E1["domains"][DOMS[0]]["procedures"].keys())
    labels = ["P1 endpoint", "P2 global-β", "P3 regime", "P4 oracle",
              "P5 forced", "P6 gate"]
    colors = ['#b2182b', '#2166ac', '#92c5de', '#333333', '#f4a582',
              '#4dac26']
    for ax, dom in zip(axes, DOMS):
        ps = E1["domains"][dom]["procedures"]
        vals = [ps[k]["r20"] for k in order]
        oracle = ps["P4 oracle over gate family (upper bound)"]["r20"]
        x = np.arange(len(vals))
        bars = ax.bar(x, vals, .62, color=colors, edgecolor='white',
                      linewidth=.5)
        ax.axhline(oracle, color='#333', linestyle='--', linewidth=.9)
        lo, hi = min(vals), max(vals)
        pad = (hi - lo) * .5 + 1e-4
        ax.set_ylim(lo - pad, hi + pad * .35)
        for b, v in zip(bars, vals):
            ax.text(b.get_x() + b.get_width() / 2, v, f'{v:.4f}',
                    ha='center', va='bottom', fontsize=5.4, rotation=90)
        ax.set_xticks(x)
        ax.set_xticklabels(labels, rotation=45, ha='right', fontsize=6.5)
        ax.set_title(SHORT[dom], fontweight='bold')
        ax.grid(axis='y', alpha=.25, linewidth=.5)
        ax.set_axisbelow(True)
    axes[0].set_ylabel('Test R@20')
    fig.tight_layout()
    fig.savefig(FIGS / 'fig_e1_procedures.pdf')
    fig.savefig(FIGS / 'fig_e1_procedures.png', dpi=150)
    plt.close(fig)

    # E2: matched-teacher + swap
    fig, axes = plt.subplots(1, 2, figsize=(9.0, 3.0))
    ax = axes[0]
    conds = ['NARM\n(ID)', 'CEARF-N\n(no-meta)', 'NARM+sem\n(TF-IDF)',
             'CEARF-N\n(full)']
    vg = [.13705, .13208, .15387, .147]
    bp = [.02990, .05055, .06628, .056]
    x = np.arange(4)
    w = .38
    ax.bar(x - w / 2, vg, w, label='Video', color='#2166ac',
           edgecolor='white', linewidth=.5)
    ax.bar(x + w / 2, bp, w, label='Baby', color='#f4a582',
           edgecolor='white', linewidth=.5)
    ax.set_xticks(x)
    ax.set_xticklabels(conds, fontsize=7)
    ax.set_ylabel('R@20')
    ax.set_title('(a) Matched-information conditions', fontweight='bold',
                 fontsize=9)
    ax.legend(frameon=False)
    ax.grid(axis='y', alpha=.25, linewidth=.5)
    ax.set_axisbelow(True)
    ax = axes[1]
    doms3 = ['Video', 'Baby', 'Diginetica']
    narm_only = [E2["domains"][d]["expert_swap"]["narm_only"] for d in DOMS]
    fused = [E2["domains"][d]["expert_swap"]["dynamic"] for d in DOMS]
    x = np.arange(3)
    ax.bar(x - w / 2, narm_only, w, label='NARM expert alone',
           color='#bababa', edgecolor='white', linewidth=.5)
    ax.bar(x + w / 2, fused, w, label='gate fusion (same stack)',
           color='#2166ac', edgecolor='white', linewidth=.5)
    for xi, (n, f) in enumerate(zip(narm_only, fused)):
        ax.text(xi + w / 2, f, f'+{f - n:.4f}', ha='center', va='bottom',
                fontsize=6)
    ax.set_xticks(x)
    ax.set_xticklabels(doms3, fontweight='bold')
    ax.set_title('(b) Expert swap: fusion over strong NARM',
                 fontweight='bold', fontsize=9)
    ax.legend(frameon=False, loc='upper left')
    ax.grid(axis='y', alpha=.25, linewidth=.5)
    ax.set_axisbelow(True)
    fig.tight_layout()
    fig.savefig(FIGS / 'fig_e2_matched.pdf')
    fig.savefig(FIGS / 'fig_e2_matched.png', dpi=150)
    plt.close(fig)

    # E3: quality vs budget scatter + latency decomposition
    fig, axes = plt.subplots(1, 2, figsize=(9.5, 3.0))
    ax = axes[0]
    budget_num = {"V-SKNN": 8, "STAN": 16, "CEARF-N gate family": 15}
    markers = {'Video_Games': 'o', 'Baby_Products': 's',
               'Diginetica_HID': '^'}
    for dom in DOMS:
        xs, ys, ms = [], [], []
        for meth, m in E3["domains"][dom]["methods"].items():
            b = m["tuning_budget"]
            if isinstance(b, int):
                xs.append(b)
                ys.append(m["r20_mean"])
                ms.append(meth)
        ax.scatter(xs, ys, marker=markers[dom], s=28,
                   label=SHORT[dom], alpha=.85, edgecolor='white',
                   linewidth=.4)
        for x0, y0, name in zip(xs, ys, ms):
            if name in ('CEARF-N', 'NARM', 'STAN', 'V-SKNN'):
                ax.annotate(name.replace('_native', ''), (x0, y0),
                            textcoords='offset points', xytext=(4, 3),
                            fontsize=5.8)
    ax.set_xlabel('Validation budget (cells)')
    ax.set_ylabel('Test R@20')
    ax.set_title('(a) Quality vs tuning budget', fontweight='bold',
                 fontsize=9)
    ax.legend(frameon=False)
    ax.grid(alpha=.25, linewidth=.5)
    ax.set_axisbelow(True)
    ax = axes[1]
    comps = ['gate', 'fusion', 'expert\nretrieval']
    vid = E3["domains"]["Video_Games"]["cearfn_serving_latency"]
    baby = E3["domains"]["Baby_Products"]["cearfn_serving_latency"]
    digi = E3["domains"]["Diginetica_HID"]["cearfn_serving_latency"]
    vals = np.array([[vid['gate_us'] / 1000, vid['post_us'] / 1000,
                      vid['expert_ms']],
                     [baby['gate_us'] / 1000, baby['post_us'] / 1000,
                      baby['expert_ms']],
                     [digi['gate_us'] / 1000, digi['post_us'] / 1000,
                      digi['expert_ms']]])
    x = np.arange(3)
    w = .26
    for i, (dom, c) in enumerate(zip(DOMS,
                                     ['#92c5de', '#2166ac', '#08306b'])):
        ax.bar(x + (i - 1) * w, vals[i], w, label=SHORT[dom], color=c,
               edgecolor='white', linewidth=.5)
    ax.set_yscale('log')
    ax.set_xticks(x)
    ax.set_xticklabels(comps, fontsize=7.5)
    ax.set_ylabel('ms/query (log)')
    ax.set_title('(b) CEARF-N serving decomposition', fontweight='bold',
                 fontsize=9)
    ax.legend(frameon=False)
    ax.grid(axis='y', alpha=.25, linewidth=.5)
    ax.set_axisbelow(True)
    fig.tight_layout()
    fig.savefig(FIGS / 'fig_e3_cost_quality.pdf')
    fig.savefig(FIGS / 'fig_e3_cost_quality.png', dpi=150)
    plt.close(fig)


if __name__ == '__main__':
    emit_e1()
    emit_e2()
    emit_e3()
    figs()
    print("emitted: 3 md + 3 tex + 3 figures into",
          OUT, PAPER, FIGS, sep='\n  ')
